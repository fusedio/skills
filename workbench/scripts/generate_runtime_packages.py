#!/usr/bin/env python3
import json
import re
import subprocess
import sys
from pathlib import Path

PACKAGES_PATH = Path(__file__).parent.parent / "skills/fused-runtime/packages.md"
EXCLUDE = {"fused", "job2", "server-rt2", "awslambdaric", "snapshot-restore-py"}
MISSING = "—"

DUMP_UDF = """@fused.udf(cache_max_age=0)
def udf():
    import json
    from importlib.metadata import distributions
    return json.dumps({d.metadata["Name"]: d.version for d in distributions() if d.metadata["Name"]})
"""


def normalize(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def live_realtime():
    result = subprocess.run(
        ["fused", "workbench", "run", "", "--stdin"],
        input=DUMP_UDF,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
        sys.exit(1)
    line = next(l for l in result.stdout.splitlines() if l.startswith('"'))
    dists = json.loads(json.loads(line))
    return {normalize(k): v for k, v in dists.items() if normalize(k) not in EXCLUDE}


def parse_existing(text):
    categories = []
    batch = {}
    section = None
    for line in text.splitlines():
        if line.startswith("### "):
            section = line[4:]
            categories.append((section, []))
        elif line.startswith("## "):
            section = line[3:] if line.startswith("## All packages") else None
        row = re.match(r"^\| ([a-z0-9][^ |]*) \| ([^|]*) \| ([^|]*) \|$", line)
        if row and section:
            name, _, batch_version = row.group(1), row.group(2).strip(), row.group(3).strip()
            if section == "All packages":
                batch[name] = batch_version
            else:
                categories[-1][1].append(name)
    return categories, batch


def table(rows):
    lines = ["| Package | realtime | batch |", "|---|---|---|"]
    lines += [f"| {name} | {rt} | {bt} |" for name, rt, bt in rows]
    return lines


def main():
    categories, batch = parse_existing(PACKAGES_PATH.read_text())
    realtime = live_realtime()
    batch = {k: v for k, v in batch.items() if v != MISSING}
    names = sorted(set(realtime) | set(batch))
    version = lambda d, n: d.get(n, MISSING)

    out = [
        "# Packages in the Fused UDF runtime images",
        "",
        "<!-- Realtime column: generated by workbench/scripts/generate_runtime_packages.py from a live UDF run. Batch column: kept from the previous lockfile-based version. Do not edit by hand. -->",
        "",
        "Python 3.12, linux x86_64. `realtime` is the default engine;",
        '`batch` is `engine="medium"`/`"large"` and other instance jobs.',
        f"`{MISSING}` means the package is not installed in that image.",
        "",
        f"Realtime: {len(realtime)} packages. Batch: {len(batch)} packages.",
        "",
        "## By category",
    ]
    for name, members in categories:
        rows = [(m, version(realtime, m), version(batch, m)) for m in members if m in realtime or m in batch]
        out += ["", f"### {name}", ""] + table(rows)

    differ = [(n, realtime[n], batch[n]) for n in names if n in realtime and n in batch and realtime[n] != batch[n]]
    out += ["", "## Different versions between images", ""] + table(differ)

    only_rt = [n for n in names if n in realtime and n not in batch]
    only_bt = [n for n in names if n in batch and n not in realtime]
    out += ["", "## Only in one image", "", "Realtime only: " + ", ".join(only_rt), "", "Batch only: " + ", ".join(only_bt)]

    out += ["", "## All packages", ""] + table([(n, version(realtime, n), version(batch, n)) for n in names])
    PACKAGES_PATH.write_text("\n".join(out) + "\n")
    print(f"Wrote {len(realtime)} realtime and {len(batch)} batch packages to {PACKAGES_PATH}")


if __name__ == "__main__":
    main()
